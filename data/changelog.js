// Helper function to format dates
export const formatChangelogDate = (dateString) => {
    const options = { year: 'numeric', month: 'long', day: 'numeric' };
    return new Date(dateString).toLocaleDateString(undefined, options);
};

// Helper function to get entries by month
export const getEntriesByMonth = (month) => {
    return CHANGELOG_ENTRIES.filter(entry => entry.month === month);
};

// Helper function to get all months
export const getAllMonths = () => {
    const months = [...new Set(CHANGELOG_ENTRIES.map(entry => entry.month))];
    return months.sort().reverse(); // Most recent first
};

// Helper function to get latest entry
export const getLatestEntry = () => {
    return CHANGELOG_ENTRIES[CHANGELOG_ENTRIES.length - 1];
};
